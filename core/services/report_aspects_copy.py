def category_for(aspect: str) -> str:
    if aspect in {"square", "opposition"}:
        return "tension"
    if aspect in {"trine", "sextile"}:
        return "resource"
    return "mixed"


def pair_key(a: str, b: str, aspect: str) -> tuple[str, str, str]:
    left, right = sorted((a, b))
    return (left, right, aspect)


def headline_for(a: str, b: str, aspect: str) -> str:
    found = PAIR_HEAD.get(pair_key(a, b, aspect))
    if found:
        return found
    want_a = PLANET_WANT.get(a, "одна потребность")
    want_b = PLANET_WANT.get(b, "другая потребность")
    cat = category_for(aspect)
    if cat == "tension":
        return f"Когда хочется {want_a} — и одновременно {want_b}"
    if cat == "resource":
        return f"Где легче совмещать: {want_a}"
    return f"Где сливаются {PLANET_FN.get(a, a)} и {PLANET_FN.get(b, b)}"


def questions_for(category: str, a: str, b: str) -> list[str]:
    want_a = PLANET_WANT.get(a, "это")
    want_b = PLANET_WANT.get(b, "другое")
    if category == "resource":
        return [
            "В каких ситуациях эта лёгкость действительно тебя держит — а где просто привычна?",
            "Что ты перестаёшь проверять, потому что «и так хорошо»?",
            "Где этот ресурс мог бы поддержать более трудную тему, а не заменять её?",
        ]
    if category == "mixed":
        return [
            f"Где ты отличаешь «мне нужно {want_a}» от «мне нужно {want_b}» — а где они уже одно?",
            "Что усиливается, когда эти две темы сливаются?",
            "Какой маленький шаг вернул бы выбор, не ломая саму связку?",
        ]
    return [
        f"В каких ситуациях сильнее включается {PLANET_FN.get(a, a)} — а где {PLANET_FN.get(b, b)}?",
        "Что именно эта привычная реакция помогает не чувствовать или не рисковать?",
        "Если обе стороны важны, какой следующий шаг не требует победы одной из них?",
    ]


