def cycle_copy(transit: str, polarity: str) -> dict[str, str]:
    block = CYCLE_COPY.get(transit) or {
        "meaning": "Цикл подсвечивает тему этой планеты в карте. Это фон, а не приговор.",
        "duration": "Длительность зависит от скорости планеты.",
        "pressure_practice": WORK_WITH["pressure"],
        "resource_practice": WORK_WITH["resource"],
        "use_for": "Чтобы наблюдать тему, а не ждать события.",
    }
    practice = (
        block["resource_practice"]
        if polarity == "resource"
        else block["pressure_practice"]
        if polarity == "pressure"
        else WORK_WITH["mixed"]
    )
    return {
        "meaning": block["meaning"],
        "duration": block["duration"],
        "practice": practice,
        "use_for": block["use_for"],
    }


def core_interpretation(point: str, sign: str) -> str:
    if point == "sun":
        return SUN_BASE.get(sign, "")
    if point == "moon":
        return MOON_BASE.get(sign, "")
    if point == "ascendant":
        return ASC_MEANINGS.get(sign, "")
    return ""


def placement_sentence(point: str, sign_ru: str, house: int | None = None, sign: str = "") -> str:
    theme = PLANET_THEME.get(point, "")
    name = PLANET_RU.get(point, point)
    house_bit = ""
    if house:
        house_bit = f" Дом {house}: {HOUSE_THEME.get(int(house), '')}."
    core = core_interpretation(point, sign)
    if core:
        return f"{core}{house_bit}".strip()
    return (
        f"{name} в {sign_ru}. В астрологии {name} связано с темой: {theme}. "
        f"{sign_ru} задаёт способ, которым эта тема обычно проявляется.{house_bit}"
    ).strip()


def aspect_sentence(transit: str, aspect_ru: str, natal: str, kind: str) -> str:
    t = PLANET_RU.get(transit, transit)
    n = PLANET_RU.get(natal, natal)
    how = ASPECT_THEME.get(kind if kind in ASPECT_THEME else "", "")
    # kind here is aspect key (conjunction), not hard/soft
    return (
        f"Транзитный {t} образует {aspect_ru} к натальному {n}. "
        f"{how.capitalize() if how else ''} "
        f"{t} приносит тему «{PLANET_THEME.get(transit, '')}», "
        f"{n} в карте отвечает за «{PLANET_THEME.get(natal, '')}»."
    ).strip()
