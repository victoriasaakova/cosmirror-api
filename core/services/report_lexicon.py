def core_interpretation(point: str, sign: str) -> str:
    if point == "sun":
        return SUN_BASE.get(sign, "")
    if point == "moon":
        return MOON_BASE.get(sign, "")
    if point == "ascendant":
        return ASC_MEANINGS.get(sign, "")
    return PLANET_LIVED.get(point, {}).get(sign, "")


def placement_sentence(point: str, sign_ru: str, house: int | None = None, sign: str = "") -> str:
    body = core_interpretation(point, sign).strip()
    if not body:
        body = _lived_fallback(point, sign_ru, sign)
    house_bit = ""
    if house:
        arena = HOUSE_ARENA.get(int(house), "")
        if arena:
            house_bit = f" Это может проявляться {arena}."
    return f"{body}{house_bit}".strip()


def _lived_fallback(point: str, sign_ru: str, sign: str) -> str:
    name = PLANET_RU.get(point, point)
    in_sign = SIGN_IN.get(sign, f"в знаке {sign_ru}" if sign_ru else "")
    need = PLANET_NEED.get(point, "эта тема")
    if in_sign:
        return (
            f"Тебе может быть важно {need}. "
            f"Положение {in_sign} — гипотеза о способе, не приговор и не каталог значения {name}."
        )
    return f"Тебе может быть важно {need}. Это гипотеза по карте, не диагноз."


def natal_aspect_sentence(a: str, aspect_key: str, aspect_ru: str, b: str) -> str:
    a_name = PLANET_RU.get(a, a)
    b_name = PLANET_RU.get(b, b)
    how = ASPECT_THEME.get(aspect_key, "")
    how_bit = f"{how.capitalize()}. " if how else ""
    return (
        f"В карте {a_name} и {b_name} связаны через {aspect_ru}. "
        f"{how_bit}"
        "Это внутренняя связка тем, не событие снаружи."
    )


def aspect_sentence(transit: str, aspect_ru: str, natal: str, kind: str) -> str:
    t = PLANET_RU.get(transit, transit)
    n = PLANET_RU.get(natal, natal)
    how = ASPECT_THEME.get(kind if kind in ASPECT_THEME else "", "")
    # kind here is aspect key (conjunction), not hard/soft
    return (
        f"Транзитный {t} образует {aspect_ru} к натальному {n}. "
        f"{how.capitalize() if how else ''} "
        f"{t} приносит тему «{PLANET_THEME.get(transit, '')}», "
        f"{n} в карте отвечает за «{PLANET_THEME.get(natal, '')}»."
    ).strip()
